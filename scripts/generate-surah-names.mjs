/**
 * Regenerates `src/lib/quran/surahNames.ts` from the corpus.
 *
 * The reader loads chapter data at runtime; this table exists so the *build*
 * does not have to. It generates the 114 routes and their page titles, and it
 * must keep working when the network does not.
 *
 *   node scripts/generate-surah-names.mjs
 */
import { writeFile } from "node:fs/promises";

const ENDPOINT = "https://api.quran.com/api/v4/chapters?language=en";
const TARGET = new URL("../src/lib/quran/surahNames.ts", import.meta.url);

const response = await fetch(ENDPOINT);
if (!response.ok) throw new Error(`chapters endpoint responded ${response.status}`);

const { chapters } = await response.json();
if (!Array.isArray(chapters) || chapters.length !== 114) {
  throw new Error(`expected 114 chapters, received ${chapters?.length}`);
}

const rows = chapters
  .sort((a, b) => a.id - b.id)
  .map(
    (c) =>
      `  { english: ${JSON.stringify(c.name_simple)}, arabic: ${JSON.stringify(c.name_arabic)}, ` +
      `meaning: ${JSON.stringify(c.translated_name.name)}, ayat: ${c.verses_count}, ` +
      `place: ${JSON.stringify(c.revelation_place)} },`,
  )
  .join("\n");

const file = `/**
 * The 114 surahs, baked in at build time.
 *
 * The reader gets its live chapter data from the corpus, but the *routes* and
 * their metadata are generated statically: a link to a surah has to be a real
 * page with a real title in a search result, and the build must not depend on
 * a third party's uptime.
 *
 * Generated by scripts/generate-surah-names.mjs — run \`npm run gen:surahs\`.
 */

export interface SurahName {
  english: string;
  arabic: string;
  meaning: string;
  ayat: number;
  place: string;
}

export const SURAH_NAMES: SurahName[] = [
${rows}
];
`;

await writeFile(TARGET, file, "utf8");
console.log(`wrote ${chapters.length} surahs to src/lib/quran/surahNames.ts`);
